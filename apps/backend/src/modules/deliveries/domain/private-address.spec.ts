import { isPrivateAddress } from './private-address';

describe('isPrivateAddress', () => {
	it.each([
		['자기 자신', '127.0.0.1'],
		['자기 자신(다른 표기)', '127.1.2.3'],
		['0.0.0.0', '0.0.0.0'],
		['클라우드 메타데이터', '169.254.169.254'],
		['사설망 10.x', '10.0.1.5'],
		['사설망 172.16~31', '172.16.0.1'],
		['사설망 172.31', '172.31.255.255'],
		['사설망 192.168.x', '192.168.0.10'],
		['통신사 공유 주소', '100.64.0.1'],
		['멀티캐스트', '224.0.0.1'],
		['브로드캐스트', '255.255.255.255'],
		['IPv6 자기 자신', '::1'],
		['IPv6 지정 안 됨', '::'],
		['IPv6 사설망', 'fd12:3456:789a::1'],
		['IPv6 링크 로컬', 'fe80::1'],
		['IPv4를 감싼 IPv6 (자기 자신)', '::ffff:127.0.0.1'],
		['IPv4를 감싼 IPv6 (사설망)', '::ffff:10.0.0.1'],
		['IPv4를 감싼 IPv6 (메타데이터)', '::ffff:169.254.169.254'],
	])('막는다 — %s (%s)', (_name, ip) => {
		expect(isPrivateAddress(ip)).toBe(true);
	});

	it.each([
		['공인 IPv4', '8.8.8.8'],
		['공인 IPv4', '52.78.5.241'],
		['사설망 바로 밖 172.15', '172.15.255.255'],
		['사설망 바로 밖 172.32', '172.32.0.0'],
		['사설망 바로 밖 11.x', '11.0.0.1'],
		['링크 로컬 바로 밖', '169.255.0.1'],
		['공인 IPv6', '2606:4700:4700::1111'],
		['공인 IPv4를 감싼 IPv6', '::ffff:8.8.8.8'],
	])('보낸다 — %s (%s)', (_name, ip) => {
		expect(isPrivateAddress(ip)).toBe(false);
	});
});
